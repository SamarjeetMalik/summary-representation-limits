"""Tables and macros for the MLST manuscript (mlst.tex).

Writes tables/j_*.tex and appends macros to tables/values.tex. Run after the other
make_tables_* scripts and after run_nkg_baseline, run_bayes, run_probe_calibration and
run_selection_robustness. Blocks that are missing from results.json are skipped with a
warning, and the manuscript then fails to build on the undefined macro: loudly, by design.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(os.path.dirname(HERE), 'tables')
R = json.load(open(os.path.join(HERE, 'results.json')))
M = {}


def f4(v):
    return '%.4f' % v


def write(name, body):
    open(os.path.join(TAB, name), 'w', encoding='utf-8').write(
        '%% generated by analysis/make_tables_journal.py from results.json; do not edit\n' + body)
    print('  tables/%s' % name)


def sd_cell(e):
    if e.get('seeds', 0) == 0:
        return 'fixed'
    if e['sd'] == 0:
        return r'$<10^{-4}$'
    return '$%.4f$' % e['sd']


# ------------------------------------------------------------- Table: estimators
E = R['estimators']
B = R.get('bayes')
rows = [('Ridge (10 coefficients)', 'Ridge', 'deterministic'),
        ('Random forest', 'RandomForest', ''),
        ('Gradient boosting', 'GradBoost', ''),
        (r'MLP $64{\times}64$', 'MLP', ''),
        (r'Size--age calibration (2 coefficients)', 'NKG', 'archived'),
        (r'Archived CNN/ViT, rendered input', 'CNN/ViT', 'archived')]
body = []
for lbl, k, note in rows:
    sd = 'deterministic' if note == 'deterministic' else ('---' if note == 'archived' else sd_cell(E[k]))
    body.append(r'%s & $%s$ & %s \\' % (lbl, f4(E[k]['sigma']), sd))
    if k == 'MLP':
        body.append(r'\midrule')
bayes_row = ''
if B:
    bayes_row = (r'\midrule' '\n' r'\emph{Bayes floor, nine features (Gamma test)} & $%s$ & $[%s,%s]$ \\'
                 % (f4(B['nine']['rms_floor']), f4(B['nine']['ci'][0]), f4(B['nine']['ci'][1])))
write('j_floor.tex', r"""\begin{table}[t]
\centering
\caption{Every estimator on the same %s events. $\sigma$ is the standard deviation of
$\hat y-y$ with $y=\lgE$. The third column is the seed-to-seed standard deviation over five
seeds (ridge has no seed; archived rows are fixed predictions). The last row is the
model-free estimate of the Bayes floor of the nine-feature representation
(section~\ref{sec:bayes}) with its $95\%%$ bootstrap interval.}
\label{tab:floor}
\begin{tabular}{lcc}
\toprule
Estimator & $\sigma(\lgE)$ & seed s.d.\ / interval \\
\midrule
%s
%s
\bottomrule
\end{tabular}
\end{table}
""" % (R['n_matched'] and '{:,}'.format(R['n_matched']).replace(',', '{,}'), '\n'.join(body), bayes_row))

# ------------------------------------------------------------- Table: rendering + sweep
RD, SW = R['rendering'], R['sweep']
pred = {'A': 0.1234, 'B': 0.1234, 'C': 0.1063, 'D': 0.1019}
rr = [('A', 'four fit scalars, gradient boosting', RD['A_scalars4'], pred['A']),
      ('B', 'CNN on rendered image', RD['B_rendered'], pred['B']),
      ('C', r'CNN on rendered image $+$ 16 muon counts', RD['C_rendered_muon'], pred['C']),
      ('D', 'nine features, gradient boosting', RD['D_nine'], pred['D'])]
if 'tab_phi_mu' in RD:
    rr.insert(3, ("C$'$", r'four scalars $+$ 16 muon counts, gradient boosting', RD['tab_phi_mu'], None))
    rr.insert(4, ("C$''$", r'as C$^\prime$ $+$ zenith angle', RD['tab_phi_mu_theta'], None))
    M.update({'rendCtab': f4(RD['tab_phi_mu']), 'rendCtabTheta': f4(RD['tab_phi_mu_theta'])})
M['rendMaxBelowA'] = f4(max(RD['A_scalars4'] - RD['B_rendered'], RD['A_scalars4'] - SW['G_vit_patches'], 0))
sr = [('E', 'ridge on the 400 pixels', 'linear', SW['E_ridge_pixels']),
      ('F', 'MLP on the 400 pixels', 'fully connected', SW['F_mlp_pixels']),
      ('B', 'CNN on the image', 'convolutional', RD['B_rendered']),
      ('G', r'ViT on $4{\times}5$ patches', 'attention', SW['G_vit_patches'])]
floor4 = (r'\midrule' '\n' r'& \emph{Bayes floor, four scalars (Gamma test)} & --- & $%s$ \\'
          % f4(B['four']['rms_floor'])) if B else ''
write('j_render.tex', r"""\begin{table}[t]
\centering
\caption{Reconstructing the failure. All rows train on the same %s-event subsample of
the training complement and are scored on the matched population. The predicted column was
written down before rows A to D were run; rows C$'$ and C$''$ are tabular controls added
afterwards, with the information content of row C and of row C plus the zenith angle. Row D differs from gradient boosting in
table~\ref{tab:floor} ($%s$) only because of the smaller training set.}
\label{tab:render}
\begin{tabular}{llcc}
\toprule
& Input and model & predicted & observed \\
\midrule
%s
%s
\bottomrule
\end{tabular}
\end{table}
""" % ('{:,}'.format(RD['n_train']).replace(',', '{,}'), f4(E['GradBoost']['sigma']),
       '\n'.join(r'%s & %s & %s & $%s$ \\' % (a, b, '---' if p is None else '$%s$' % f4(p), f4(o))
                 for a, b, o, p in rr), floor4))

write('j_sweep.tex', r"""\begin{table}[t]
\centering
\caption{Four architecture classes on the identical rendered input (the reference is row A
of table~\ref{tab:render}, $%s$). Row labels continue table~\ref{tab:render}.}
\label{tab:sweep}
\begin{tabular}{lllc}
\toprule
& Model & class & $\sigma(\lgE)$ \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % (f4(RD['A_scalars4']), '\n'.join(r'%s & %s & %s & $%s$ \\' % (a, b, c, f4(v)) for a, b, c, v in sr)))

# ------------------------------------------------------------- Table: probe calibration
P = R.get('probe_calibration')
if P:
    rows = P['rows']
    order = [('gb_phi', r'gradient boosting on $\phi$', r'$\phi$'),
             ('linear_Ne_s', r'size--age calibration', r'$\phi$ (exact)'),
             ('cnn_rendered', 'CNN, rendered image (B)', r'$\phi$'),
             ('vit_rendered', 'ViT, rendered image (G)', r'$\phi$'),
             ('cnn_rendered_muon', r'CNN, rendered $+$ muons (C)', r'$\phi$, $M$'),
             ('gb_nine', 'gradient boosting, nine features', r'$\phi$, $M$'),
             ('true_energy', r'true energy (not a model)', '---')]
    body = [r'%s & %s & $%s$ & $%s$ & $%+.4f$ \\' % (lbl, src, f4(rows[k]['phi']), f4(rows[k]['phi_M']),
                                                       rows[k]['increment']) for k, lbl, src in order]
    body.append(r'\midrule')
    for tau, r_ in P['noise'].items():
        body.append(r'GB on $\phi$ $+\,\mathcal{N}(0,%s^2)$ & $\phi$, noise & $%s$ & $%s$ & $%+.4f$ \\'
                    % (tau, f4(r_['phi']), f4(r_['phi_M']), r_['increment']))
    for lam, r_ in P['mix'].items():
        body.append(r'$(1-%s)\,$GB$(\phi)+%s\,u(M)$ & $\phi$, $M$ & $%s$ & $%s$ & $%+.4f$ \\'
                    % (lam, lam, f4(r_['phi']), f4(r_['phi_M']), r_['increment']))
    a = rows['archived']
    body += [r'\midrule',
             r'\textbf{archived CNN/ViT} & unknown & $\mathbf{%s}$ & $\mathbf{%s}$ & $\mathbf{%+.4f}$ \\'
             % (f4(a['phi']), f4(a['phi_M']), a['increment'])]
    write('j_probe.tex', r"""\begin{table}[t]
\centering\small
\caption{Calibrating the degeneracy probe. Each row regresses a model's own output on the
fitted parameters $\phi$, then on $\phi$ plus the other measured channels $M$ (16 muon counts
and zenith angle), with out-of-fold gradient boosting on the matched population. Information
from outside $\phi$ lowers $R^2(\phi)$ but not $R^2(\phi,M)$; noise lowers both. The
retrain ceiling (two seeds of the same CNN) is $R^2=%s$.}
\label{tab:probe}
\begin{tabular}{llccc}
\toprule
Output probed & true inputs & $R^2(\phi)$ & $R^2(\phi,M)$ & increment \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % (f4(P['retrain_ceiling']), '\n'.join(body)))
    cm = rows['cnn_rendered_muon']
    M['probeArchVsC'] = '%.3f' % max(abs(a['phi'] - cm['phi']), abs(a['phi_M'] - cm['phi_M']))
    M.update({'probeArchPhi': '%.3f' % a['phi'], 'probeArchPhiM': '%.3f' % a['phi_M'],
              'probeArchTrueE': '%.3f' % a['phi_M_trueE'],
              'probeLinPhi': '%.3f' % rows['linear_Ne_s']['phi'],
              'probeCnnPhi': '%.3f' % rows['cnn_rendered']['phi'],
              'probeCnnMuPhi': '%.3f' % rows['cnn_rendered_muon']['phi'],
              'probeCnnMuPhiM': '%.3f' % rows['cnn_rendered_muon']['phi_M'],
              'probeRetrain': '%.4f' % P['retrain_ceiling']})
else:
    print('  WARNING: no probe_calibration block; j_probe.tex not written')

# ------------------------------------------------------------- Table: selection robustness
S = R.get('selection_robustness')
if S:
    rr = S['rows']
    lab = {'none': 'no selection', 'standard': r'$0.90\le s\le1.15$ (standard)',
           'wide': r'$0.90\le s\le1.40$'}
    body = []
    for cut in ('none', 'standard', 'wide'):
        a, w = rr['%s|all ages' % cut], rr['%s|within selection' % cut]
        body.append(r'%s & $%.1f\%%$ & $%s$ & $%s$ & $%s$ \\' % (
            lab[cut], a['kept'], f4(a['sigma']), f4(w['sigma']), f4(w['bias_spread'])))
    write('j_selection.tex', r"""\begin{table}[t]
\centering
\caption{The standard selection under the two ways an analyst could apply it: scoring a model
trained on all ages, or retraining on the accepted events only. The last column is the spread
(maximum minus minimum) of the mean bias across the five primaries, for the retrained model;
a quality cut is meant to reduce it. Mean over %d seeds.}
\label{tab:selection}
\begin{tabular}{lcccc}
\toprule
Selection & kept & $\sigma$, trained on all & $\sigma$, trained within & bias spread \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % (S['seeds'], '\n'.join(body)))
    M.update({'biasSpreadNone': f4(rr['none|within selection']['bias_spread']),
              'biasSpreadStd': f4(rr['standard|within selection']['bias_spread']),
              'sigmaStdWithin': f4(rr['standard|within selection']['sigma'])})
else:
    print('  WARNING: no selection_robustness block; j_selection.tex not written')

# ------------------------------------------------------------- KCDC arm (second experiment)
KP = os.path.join(HERE, 'kcdc', 'kcdc_results.json')
if os.path.exists(KP):
    K = json.load(open(KP))
    rows, corrs, deltas = [], [], []
    for lbl, v in K['selection'].items():
        n_, c_ = v['none'], v['central half of age']
        d_ = 100 * (c_['sigma_trained_within'] - n_['sigma_trained_within']) / n_['sigma_trained_within']
        corrs.append(abs(v['corr_age_logE'])); deltas.append(d_)
        name = 'full range' if lbl == 'full range' else r'$%s$' % lbl.replace('logNe ', '').replace('-', '$--$')
        rows.append(r'%s & $%s$ & $%+.3f$ & $%s$ & $%s$ & $%+.1f\%%$ & $%s\to%s$ \\' % (
            name, '{:,}'.format(v['n']).replace(',', '{,}'), v['corr_age_logE'],
            f4(n_['sigma_trained_within']), f4(c_['sigma_trained_within']), d_,
            f4(n_['bias_spread']), f4(c_['bias_spread'])))
        if lbl == 'full range':
            rows.append(r'\midrule')
    write('j_kcdc.tex', r"""\begin{table}[t]
\centering\small
\caption{The selection question on a second experiment: KASCADE simulation from the KCDC
(CORSIKA with QGSJET-II-04, five primaries, $\lgE\in[5,6]$). Rows are slices of width $0.4$ in
reconstructed $\log_{10}\Ne$; the selection keeps the central half of the age distribution, and
the model is retrained within it. Within slices age carries almost no energy information here,
unlike GRAPES-3, and the selection's effect on $\sigma$ changes sign across slices. At most
$400{,}000$ events per row.}
\label{tab:kcdc}
\begin{tabular}{lrcccrc}
\toprule
$\log_{10}\Ne$ slice & events & corr$(s,\lgE)$ & $\sigma$, none & $\sigma$, central age & change & bias spread \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % '\n'.join(rows))
    sl = [v for k, v in K['selection'].items() if k != 'full range']
    M.update({'kcdcMaxAbsCorr': '%.2f' % max(abs(v['corr_age_logE']) for v in sl),
              'kcdcDeltaMin': '%.0f' % min(deltas), 'kcdcDeltaMax': '%+.0f' % max(deltas),
              'kcdcNslices': str(len(sl))})
    KPr = K['probe']
    M.update({'kcdcProbeGB': '%.3f' % KPr['GB on phi']['phi'],
              'kcdcNoiseMaxInc': '%.4f' % max(abs(KPr[k]['increment']) for k in KPr if 'N(0' in k),
              'kcdcMixInc': '%.3f' % KPr['(1-0.5) GB(phi) + 0.5 u(M)']['increment'],
              'kcdcMixPhi': '%.3f' % KPr['(1-0.5) GB(phi) + 0.5 u(M)']['phi'],
              'kcdcMixPhiM': '%.3f' % KPr['(1-0.5) GB(phi) + 0.5 u(M)']['phi_M']})
else:
    print('  WARNING: no analysis/kcdc/kcdc_results.json; KCDC table and macros skipped')

# ------------------------------------------------------------- macros
NB = R['nkg_baseline']
M.update({
    'nkgCoefNe': '%.3f' % NB['archived_coef'][0], 'nkgCoefAge': '%.3f' % NB['archived_coef'][1],
    'nkgRefit': f4(NB['refit']['logNe_age']['sigma']),
    'nkgSizeOnly': f4(NB['refit']['logNe']['sigma']),
    'nkgSizeSec': f4(NB['refit']['logNe_sec']['sigma']),
    'seedSdMLP': f4(E['MLP']['sd']),
    'Ncsv': '{:,}'.format(R['n_csv']).replace(',', '{,}'),
})
if B:
    M.update({'bayesNine': f4(B['nine']['rms_floor']), 'bayesNineLo': f4(B['nine']['ci'][0]),
              'bayesNineHi': f4(B['nine']['ci'][1]), 'bayesFour': f4(B['four']['rms_floor']),
              'bayesFourLo': f4(B['four']['ci'][0]), 'bayesFourHi': f4(B['four']['ci'][1]),
              'bayesGapPct': '%.1f' % (100 * (E['GradBoost']['sigma'] - B['nine']['rms_floor'])
                                       / B['nine']['rms_floor']),
              'bayesCtrlWorst': '%.1f' % max(100 * abs(c_['est_sd'] - c_['true_sd']) / c_['true_sd']
                                             for c_ in B['controls'])})
sp = {s['name']: s for s in R['species']}
M.update({'fracOldIron': '%.1f' % sp['iron']['frac_old'], 'fracOldProton': '%.1f' % sp['proton']['frac_old']})

existing = open(os.path.join(TAB, 'values.tex'), encoding='utf-8').read()
open(os.path.join(TAB, 'values.tex'), 'w', encoding='utf-8').write(
    existing + '\n'.join(r'\newcommand{\%s}{%s}' % kv for kv in M.items()) + '\n')
print('  +%d MLST macros appended to tables/values.tex' % len(M))
