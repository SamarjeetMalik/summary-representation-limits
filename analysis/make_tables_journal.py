def f4(v):
    return '%.4f' % v


def write(name, body):
    open(os.path.join(TAB, name), 'w', encoding='utf-8').write(
        '%% generated by analysis/make_tables_journal.py from results.json; do not edit\n' + body)
    print('  tables/%s' % name)


def sd_cell(e):
    if e.get('seeds', 0) == 0:
        return 'fixed'
    if e['sd'] == 0:
        return r'$<10^{-4}$'
    return '$%.4f$' % e['sd']


