def np_mean(v):
    return sum(v) / len(v)


def s1(v):
    """signed one-decimal value without a negative zero"""
    v = 0.0 if abs(v) < 0.05 else v
    return ('%+.1f' % v) if v else '0.0'


def f4(v):
    return '%.4f' % v


def num(n):
    return '{:,}'.format(n).replace(',', '{,}')


def load(name):
    return json.load(open(os.path.join(K, name)))


def write(name, body):
    open(os.path.join(TAB, name), 'w', encoding='utf-8').write(
        '%% generated by analysis/make_tables_epjc.py from analysis/kcdc/*.json; do not edit\n' + body)
    print('  tables/%s' % name)


def vshare(g, o, x):
    """Share of the variance gap between g (nine features) and o (oracle) that x closes, in %."""
    return 100 * (g ** 2 - x ** 2) / (g ** 2 - o ** 2)


