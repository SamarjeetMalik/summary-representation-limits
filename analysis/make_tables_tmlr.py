def np_mean(v):
    return sum(v) / len(v)


def f4(v):
    return '%.4f' % v


def num(n):
    return '{:,}'.format(n).replace(',', '{,}')


def sd_cell(e):
    return r'$<10^{-4}$' if e['sd'] == 0 else '$%.4f$' % e['sd']


def write(name, body):
    open(os.path.join(TAB, name), 'w', encoding='utf-8').write(
        '%% generated by analysis/make_tables_tmlr.py from results.json; do not edit\n' + body)
    print('  tables/%s' % name)


